/**
 Reads camera specs (date, camera, aperture, shutter, ISO, focal length)
 from the EXIF of the original photos in legacy/assets/images and writes
 src/content/photo-specs.ts for the gallery. GPS is deliberately never read:
 members' photo locations stay private. Run with `pnpm photo-specs`.
 */

/* eslint-disable no-await-in-loop -- sequential on purpose to keep memory low. */

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

type Spec = {
	camera?: string;
	date?: string;
	aperture?: string;
	shutter?: string;
	iso?: number;
	focal?: string;
};

const source = path.resolve("legacy/assets/images");

type Tags = Map<number, string | number>;

const sizes: Record<number, number> = { 2: 1, 3: 2, 4: 4, 5: 8 };

function readEntry(
	tiff: ReturnType<typeof Buffer.from>,
	entry: number,
	u16: (offset: number) => number,
	u32: (offset: number) => number
): [number, string | number] | undefined {
	const tag = u16(entry);
	const type = u16(entry + 2);
	const length = u32(entry + 4);
	const size = sizes[type];
	if (size === undefined) {
		return undefined;
	}

	const valueOffset = size * length <= 4 ? entry + 8 : u32(entry + 8);
	if (valueOffset + size * length > tiff.length) {
		return undefined;
	}

	switch (type) {
		case 2: {
			const text = tiff
				.toString("ascii", valueOffset, valueOffset + length)
				.replaceAll("\0", "")
				.trim();
			return [tag, text];
		}

		case 3: {
			return [tag, u16(valueOffset)];
		}

		case 4: {
			return [tag, u32(valueOffset)];
		}

		default: {
			const denominator = u32(valueOffset + 4);
			return [tag, denominator === 0 ? 0 : u32(valueOffset) / denominator];
		}
	}
}

function parseExif(exif: Uint8Array): Spec {
	const raw = Buffer.from(exif);
	const tiff = raw.subarray(raw.indexOf("Exif\0\0") === 0 ? 6 : 0);
	if (tiff.length < 8) {
		return {};
	}

	const isLittle = tiff.toString("ascii", 0, 2) === "II";
	const u16 = (offset: number) =>
		isLittle ? tiff.readUInt16LE(offset) : tiff.readUInt16BE(offset);
	const u32 = (offset: number) =>
		isLittle ? tiff.readUInt32LE(offset) : tiff.readUInt32BE(offset);

	const readIfd = (offset: number): Tags => {
		const tags: Tags = new Map();
		if (offset + 2 > tiff.length) {
			return tags;
		}

		const count = u16(offset);
		for (let index = 0; index < count; index++) {
			const entry = offset + 2 + index * 12;
			const result =
				entry + 12 > tiff.length ? undefined : readEntry(tiff, entry, u16, u32);
			if (result !== undefined) {
				tags.set(...result);
			}
		}

		return tags;
	};

	const text = (tags: Tags, tag: number) => {
		const value = tags.get(tag);
		return typeof value === "string" && value !== "" ? value : undefined;
	};

	const number = (tags: Tags, tag: number) => {
		const value = tags.get(tag);
		return typeof value === "number" && value > 0 ? value : undefined;
	};

	const ifd0 = readIfd(u32(4));
	const exifPointer = number(ifd0, 0x87_69);
	const exifTags: Tags =
		exifPointer === undefined
			? new Map<number, string | number>()
			: readIfd(exifPointer);

	const make = text(ifd0, 0x01_0f) ?? "";
	const model = text(ifd0, 0x01_10) ?? "";
	const camera = model.startsWith(make) ? model : `${make} ${model}`.trim();
	const date = /^(?<year>\d{4}):(?<month>\d{2}):(?<day>\d{2})/u.exec(
		text(exifTags, 0x90_03) ?? ""
	)?.groups;
	const fNumber = number(exifTags, 0x82_9d);
	const exposure = number(exifTags, 0x82_9a);
	const iso = number(exifTags, 0x88_27);
	const focal = number(exifTags, 0xa4_05) ?? number(exifTags, 0x92_0a);

	return {
		...(camera !== "" && { camera }),
		...(date !== undefined && { date: `${date.year}-${date.month}-${date.day}` }),
		...(fNumber !== undefined && { aperture: `ƒ/${Number(fNumber.toFixed(1))}` }),
		...(exposure !== undefined && {
					shutter:
						exposure >= 1 ? `${exposure}s` : `1/${Math.round(1 / exposure)}s`,
				}),
		...(iso !== undefined && { iso }),
		...(focal !== undefined && { focal: `${Math.round(focal)}mm` }),
	};
}

function camelCase(name: string) {
	return name.replaceAll(/-\w/gu, (match) => match.slice(1).toUpperCase());
}

// Original → optimized name pairs, taken from the image script.
const script = await readFile(path.resolve("scripts/optimize-images.ts"), "utf8");
const pairs = script
	.matchAll(
		/"(?<file>[^"]+\.(?:jpe?g|png|webp))":\s*"(?<name>(?:gallery|spotlight)-[\d\-a-z]+)"/gu
	)
	.toArray();

const specs: Record<string, Spec> = {};
for (const { groups } of pairs) {
	const { file, name } = groups!;
	const metadata = await sharp(path.join(source, file)).metadata();
	if (!metadata.exif) {
		continue;
	}

	const spec = parseExif(metadata.exif);
	if (Object.keys(spec).length > 0) {
		specs[camelCase(name)] = spec;
	}
}

const output = `// Generated by scripts/photo-specs.ts from the originals' EXIF. GPS is
// never read. Photos without camera metadata are simply absent.

export type PhotoSpec = {
	camera?: string;
	date?: string;
	aperture?: string;
	shutter?: string;
	iso?: number;
	focal?: string;
};

export const photoSpecs: Partial<Record<string, PhotoSpec>> = ${JSON.stringify(specs, undefined, "\t")};
`;
await writeFile(path.resolve("src/content/photo-specs.ts"), output);
console.log(`Wrote specs for ${Object.keys(specs).length} photos.`);
